/**
 * Postgres, one schema per app (`miniapp_<name>` by default). Bring a pool:
 * anything with `connect()` returning a client with `query(config)` and
 * `release()` — node-postgres' `Pool` as it is — so this package does not
 * depend on a driver. The pool stays yours; `close()` does not end it.
 *
 * Statements run with `search_path` set to the app's schema, inside a
 * transaction, so a method's SQL never names a schema and one app cannot see
 * another's tables.
 */

import { AsyncLocalStorage } from "node:async_hooks";
import { nativeMigrate } from "./native";
import { autoKey } from "../schema";
import type { Schema } from "../types";
import {
  q,
  standardLiteral,
  type AppStorage,
  type Backend,
  type Dialect,
  type MigrateOptions,
  type Row,
  type StructuralOp,
} from "./backend";

export interface PgQueryConfig {
  text: string;
  values?: unknown[];
  /** node-postgres' per-query type parsers. */
  types?: { getTypeParser(oid: number, format?: string): (value: string) => unknown };
}

export interface PgClientLike {
  query(config: PgQueryConfig): Promise<{ rows: Row[] }>;
  release(): void;
}

export interface PgPoolLike {
  connect(): Promise<PgClientLike>;
}

export interface PostgresBackendOptions {
  pool: PgPoolLike;
  /** Schema name prefix. Default `miniapp_`. */
  schemaPrefix?: string;
}

const dialect: Dialect = {
  type: (t) =>
    ({ text: "text", integer: "bigint", real: "double precision", boolean: "boolean", json: "jsonb", timestamp: "timestamptz" })[t],
  literal: (v, t) => standardLiteral(v, t, (j) => `'${JSON.stringify(j).replace(/'/g, "''")}'::jsonb`),
  autoKey: () => "GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
};

// Parsers for the types a mini app produces, so values come back as they do
// on the other backends: `count(*)` and bigint keys as numbers rather than
// strings, timestamps as ISO strings rather than Dates. Supplied per query, so
// the pool's own parsers are left alone. Anything else stays text.
const number = (v: string) => Number(v);
const PARSERS: Record<number, (v: string) => unknown> = {
  16: (v) => v === "t",
  20: number, // int8
  21: number, // int2
  23: number, // int4
  700: number, // float4
  701: number, // float8
  1700: number, // numeric
  114: (v) => JSON.parse(v), // json
  3802: (v) => JSON.parse(v), // jsonb
  1114: (v) => new Date(`${v.replace(" ", "T")}Z`).toISOString(), // timestamp
  1184: (v) => new Date(v.replace(" ", "T").replace(/([+-]\d\d)$/, "$1:00")).toISOString(), // timestamptz
};
const types = { getTypeParser: (oid: number) => PARSERS[oid] ?? ((v: string) => v) };

// node-postgres turns a JS array into a Postgres array literal, which a jsonb
// column rejects; send JSON text and let the column parse it.
function encode(v: unknown): unknown {
  if (v === undefined) return null;
  if (v !== null && typeof v === "object" && !(v instanceof Date) && !(v instanceof Uint8Array)) return JSON.stringify(v);
  return v;
}

class PostgresAppStorage implements AppStorage {
  /**
   * The transaction a statement belongs to is the one whose callback it runs
   * inside — tracked per async context rather than on the object, so a read
   * that arrives while an action is open (another app's `apps.query`) gets a
   * connection of its own instead of joining the action's transaction.
   */
  private tx = new AsyncLocalStorage<PgClientLike>();

  constructor(
    private pool: PgPoolLike,
    private schema: string,
  ) {}

  async query(sql: string, params: unknown[] = []): Promise<Row[]> {
    const run = (client: PgClientLike) => client.query({ text: sql, values: params.map(encode), types }).then((r) => r.rows);
    const current = this.tx.getStore();
    if (current) return run(current);
    return this.transaction(() => run(this.tx.getStore()!));
  }

  async transaction<T>(fn: () => Promise<T>): Promise<T> {
    const client = await this.pool.connect();
    try {
      await client.query({ text: "BEGIN" });
      await client.query({ text: `SET LOCAL search_path TO ${q(this.schema)}` });
      const out = await this.tx.run(client, fn);
      await client.query({ text: "COMMIT" });
      return out;
    } catch (err) {
      await client.query({ text: "ROLLBACK" }).catch(() => {});
      throw err;
    } finally {
      client.release();
    }
  }

  async migrate(ops: StructuralOp[], before: Schema, opts: MigrateOptions = {}): Promise<void> {
    await nativeMigrate(async (sql) => void (await this.query(sql)), dialect, ops, before, opts);
  }

  /**
   * An identity column does not advance past an id inserted explicitly (seed
   * rows, say), so the next assigned key would collide. Move each sequence
   * past the largest key.
   */
  async syncKeys(schema: Schema): Promise<void> {
    for (const [table, def] of Object.entries(schema)) {
      const key = autoKey(def);
      if (!key) continue;
      await this.query(
        `SELECT setval(pg_get_serial_sequence($1, $2), coalesce((SELECT max(${q(key)}) FROM ${q(table)}), 0) + 1, false)`,
        [`${q(this.schema)}.${q(table)}`, key],
      );
    }
  }

  async close(): Promise<void> {}
}

export function postgresBackend(options: PostgresBackendOptions): Backend {
  const prefix = options.schemaPrefix ?? "miniapp_";
  const apps = new Map<string, PostgresAppStorage>();
  const admin = async (text: string) => {
    const client = await options.pool.connect();
    try {
      await client.query({ text });
    } finally {
      client.release();
    }
  };

  return {
    name: "postgres",
    capabilities: { constraints: true, jsonAsText: false },
    async open(app) {
      let storage = apps.get(app);
      if (!storage) {
        await admin(`CREATE SCHEMA IF NOT EXISTS ${q(prefix + app)}`);
        storage = new PostgresAppStorage(options.pool, prefix + app);
        apps.set(app, storage);
      }
      return storage;
    },
    async drop(app) {
      apps.delete(app);
      await admin(`DROP SCHEMA IF EXISTS ${q(prefix + app)} CASCADE`);
    },
    async close() {
      apps.clear();
    },
  };
}
